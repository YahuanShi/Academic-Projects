def matrix_is_finite(mat):
    return np.isfinite(mat).all()

def check_matrices_match_silent(test_matrix, expected_matrix, eps):
    if not matrix_is_finite(test_matrix):
        return False
    if test_matrix.shape != expected_matrix.shape:
        return False
    return np.allclose(test_matrix, expected_matrix, atol=eps)

def check_matrices_match(test_matrix, expected_matrix, indent, eps, border=0):
    if not matrix_is_finite(test_matrix):
        print(indent + 'Matrix contains nan/inf values! Division by zero? Log/sqrt/power of negative number?')
        return False
    if test_matrix.shape != expected_matrix.shape:
        print(indent + f'Matrix has wrong shape! Got {test_matrix.shape} but expected {expected_matrix.shape}')
        return False
    rows, cols = expected_matrix.shape
    for i in range(border, rows - border):
        for j in range(border, cols - border):
            if abs(float(test_matrix[i, j]) - float(expected_matrix[i, j])) > eps:
                print(indent + f'Given matrix values do not match the expected values! In element {i},{j} got {test_matrix[i, j]} but expected {expected_matrix[i, j]}')
                return False
    return True

